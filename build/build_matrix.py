def sh_quote_env(val):
    """Values are bash expressions: keep $(...) and $VAR working."""
    return '"' + str(val) + '"'


def ordered_env(env):
    """Order variables so that each one comes after the variables it uses
    ($VAR / ${VAR}), keeping the original order otherwise."""
    keys = list(env)
    deps = {k: {d for d in re.findall(r'\$\{?(\w+)', str(env[k] or '')) if d in env and d != k}
            for k in keys}
    out, done = [], set()

    def visit(k, stack=()):
        if k in done:
            return
        if k in stack:
            raise ValueError(f'circular env references: {" -> ".join(stack + (k,))}')
        for d in sorted(deps[k], key=keys.index):
            visit(d, stack + (k,))
        done.add(k)
        out.append((k, env[k]))

    for k in keys:
        visit(k)
    return out


def write(path, text, mode=0o644):
    with open(path, 'w') as fp:
        fp.write(text)
    os.chmod(path, mode)


def env_script(spec, S):
    mods = ' '.join(spec.get('modules', []))
    lines = [
        '# generated by perfsonde build_matrix.py -- sourced by build.sh and run tests',
        'if ! type module >/dev/null 2>&1; then',
        '  for f in /etc/profile.d/lmod.sh /usr/share/lmod/lmod/init/bash '
        '/etc/profile.d/modules.sh /usr/share/Modules/init/bash '
        '${LMOD_PKG:+$LMOD_PKG/init/bash} ${MODULESHOME:+$MODULESHOME/init/bash}; do',
        '    [ -f "$f" ] && . "$f" >/dev/null 2>&1 && type module >/dev/null 2>&1 && break',
        '  done',
        'fi',
        f'{S["system"].get("module_init", "module reset")} >/dev/null 2>&1 || true',
    ]
    if mods:
        lines.append(f'module load {mods} || {{ echo "perfsonde: module load failed: {mods}" >&2; '
                     'return 1 2>/dev/null || exit 1; }')
    for key, val in ordered_env(spec.get('env') or {}):
        if val is None:
            lines.append(f'unset {key}')
        else:
            lines.append(f'export {key}={sh_quote_env(val)}')
    return '\n'.join(lines) + '\n'


def git_describe(src):
    try:
        return subprocess.run(['git', '-C', src, 'describe', '--always', '--dirty', '--tags'],
                              capture_output=True, text=True, timeout=30).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return ''


def copy_source(src, dst):
    if not os.path.isdir(src):
        raise FileNotFoundError(f'source tree not found: {src}')
    os.makedirs(dst, exist_ok=True)
    if shutil.which('rsync'):
        subprocess.run(['rsync', '-a', '--delete', '--exclude=.git',
                        src.rstrip('/') + '/', dst.rstrip('/') + '/'], check=True)
    else:
        shutil.rmtree(dst)
        shutil.copytree(src, dst, symlinks=True,
                        ignore=shutil.ignore_patterns('.git'))


# --------------------------------------------------------------------------
# MPAS: add a "perfsonde_<target>" Makefile target with the overridden flags
# --------------------------------------------------------------------------

def patch_mpas_makefile(makefile, target, overrides):
    with open(makefile) as fp:
        lines = fp.read().split('\n')
    start = next((i for i, l in enumerate(lines)
                  if re.match(rf'^{re.escape(target)}:', l)), None)
    if start is None:
        raise ValueError(f'target {target!r} not found in {makefile}')
    end = start + 1
    while end < len(lines) and lines[end].strip():
        end += 1
    block = lines[start:end]
    new_name = f'perfsonde_{target}'
    block[0] = re.sub(rf'^{re.escape(target)}:', f'{new_name}:', block[0])
    todo = dict(overrides or {})
    for i, l in enumerate(block):
        m = re.match(r'^(\s*)"(\w+) =\s?(.*)"(\s*\\?)\s*$', l)
        if not m:
            continue
        var = m.group(2)
        if var == 'BUILD_TARGET':
            block[i] = f'{m.group(1)}"BUILD_TARGET = {target}"{m.group(4)}'
        elif var in todo:
            block[i] = f'{m.group(1)}"{var} = {todo.pop(var)}"{m.group(4)}'
    if todo:
        # variables the base target does not set: add them before CPPFLAGS line
        idx = next(i for i, l in enumerate(block) if '"BUILD_TARGET' in l)
        ws = re.match(r'^(\s*)', block[idx]).group(1)
        for var, val in todo.items():
            block.insert(idx, f'{ws}"{var} = {val}" \\')
    lines[start:start] = block + ['']
    with open(makefile, 'w') as fp:
        fp.write('\n'.join(lines))
    return new_name


def mpas_build_cmds(spec, S, njobs):
    m = spec.get('mpas', {})
    core = spec.get('core', 'atmosphere')
    args = [f'CORE={core}', f'OPENMP={"true" if spec.get("openmp") else "false"}']
    args += list(m.get('make_args', []))
    target = f'perfsonde_{m.get("target", "gnu")}'
    return f'''cd src
make clean CORE={core} > ../clean.log 2>&1 || true
echo "make -j {njobs} {target} {' '.join(args)}" > ../make_command.txt
make -j {njobs} {target} {' '.join(args)} > ../compile.log 2>&1
test -x {core}_model || {{ echo "{core}_model not built; see compile.log" >&2; exit 1; }}
cp -p {core}_model ../bin/atmosphere_model
grep -E '^\\s*"(FFLAGS_OPT|CFLAGS_OPT|CXXFLAGS_OPT|LDFLAGS_OPT|FFLAGS_OMP)' Makefile \\
  | sed -n '/./p' > ../flags.txt || true
cd ..
'''


# --------------------------------------------------------------------------
# WRF: pick the configure option non-interactively
# --------------------------------------------------------------------------

def wrf_configure_menu(defaults_file, sw_os=None, sw_mach=None):
    """Re-implement the option numbering of WRF arch/Config.pl.

    Returns [(number, paropt, description, settings_line)].
    """
    sw_os = sw_os or platform.system()
    sw_mach = sw_mach or platform.machine()
    menu, opt, optstr, pending = [], 1, '', []
    with open(defaults_file, errors='replace') as fp:
        for raw in fp:
            line = raw.rstrip('\n')
            if line.startswith('#ARCH') and sw_os in line and sw_mach in line:
                optstr = line[6:]
                arch_text = re.sub(r'#.*$', '', optstr)
                pending = []
                for par in PLATFORMS:
                    if par in optstr:
                        pending.append((opt, par, f'{arch_text} ({par})'))
                        opt += 1
                continue
            if not optstr:
                continue
            if line.startswith('DESCRIPTION'):
                optstr = line
            elif line.startswith('SFC'):
                val = re.sub(r' (-\S*)*$', '', re.sub(r'^SFC\s*=\s*', '', line))
                optstr = re.sub(r'DESCRIPTION\s*=\s*', '', optstr.replace('$SFC', val))
            elif line.startswith('SCC'):
                val = re.sub(r' (-\S*)*$', '', re.sub(r'^SCC\s*=\s*', '', line))
                optstr = optstr.replace('$SCC', val)
            elif line.startswith('####'):
                desc = optstr.strip()
                menu += [(n, par, desc, settings) for n, par, settings in pending]
                optstr, pending = '', []
    return menu


def wrf_pick_option(src, w):
    if w.get('configure_option'):
        return int(w['configure_option']), None, None
    menu = wrf_configure_menu(os.path.join(src, 'arch', 'configure.defaults'))
    par = w.get('parallel', 'dmpar')
    pat = re.compile(w.get('configure_match', r'^GNU \(gfortran/gcc\)$'))
    hits = [(n, d, s) for n, p, d, s in menu if p == par and pat.search(d)]
    if len(hits) != 1:
        listing = '\n'.join(f'  {n:3d}. ({p}) {d}' for n, p, d, _ in menu)
        raise ValueError(f'configure_match {pat.pattern!r} + parallel={par} matched '
                         f'{len(hits)} options (need exactly 1). Menu:\n{listing}')
    return hits[0]


def sed_escape(s):
    return s.replace('\\', '\\\\').replace('|', '\\|').replace('&', '\\&')


def wrf_build_cmds(spec, S, njobs):
    w = spec.get('wrf', {})
    src = os.path.join(builds.build_dir(spec['name']), 'src')
    num, desc, settings = wrf_pick_option(src, w)
    nest = w.get('nesting', 1)
    case = w.get('compile_case', 'em_real')
    out = ['command -v csh >/dev/null || { echo "csh/tcsh is required by WRF ./compile" >&2; exit 1; }',
           'cd src',
           './clean -a > ../clean.log 2>&1 || true',
           f'printf "%s\\n%s\\n" {num} {nest} | ./configure > ../configure.log 2>&1',
           'test -f configure.wrf || { echo "configure failed; see configure.log" >&2; exit 1; }']
    if settings:
        out.append(f'grep -qF {shlex.quote("# Settings for " + settings)} configure.wrf || '
                   f'{{ echo "configure picked the wrong option (wanted {num}: {desc})" >&2; exit 1; }}')
    for var, val in (w.get('configure_overrides') or {}).items():
        out.append(f"sed -i 's|^{var}[[:space:]]*=.*$|{var} = {sed_escape(str(val))}|' configure.wrf")
        out.append(f"grep -q '^{var} = ' configure.wrf || "
                   f"{{ echo 'override {var} not applied' >&2; exit 1; }}")
    out += [f'./compile -j {njobs} {case} > ../compile.log 2>&1 || true',
            'test -x main/wrf.exe || { echo "wrf.exe not built; see compile.log" >&2; exit 1; }',
            'cp -p main/wrf.exe ../bin/wrf.exe',
            'cp -p configure.wrf ../configure.wrf',
            "grep -E '^(FCOPTIM|FCBASEOPTS_NO_G|CFLAGS_LOCAL|LDFLAGS_LOCAL|OMP|OMPCC|DM_FC|DM_CC|"
            "ARCH_LOCAL|PNETCDF|NETCDFPATH)[[:space:]]*=' configure.wrf > ../flags.txt || true",
            'cd ..']
    return '\n'.join(out) + '\n', num, desc


def build_script(spec, S, njobs):
    d = builds.build_dir(spec['name'])
    exe = builds.EXE[spec['model']]
    if spec['model'] == 'mpas':
        body = mpas_build_cmds(spec, S, njobs)
    else:
        body, _, _ = wrf_build_cmds(spec, S, njobs)
    return f'''#!/bin/bash
# generated by perfsonde build_matrix.py for {spec['name']}
set -eo pipefail
cd {shlex.quote(d)}
BDIR=$(pwd)
rm -f BUILD_OK BUILD_FAILED
echo "$(hostname) $$ $(date -Is)" > BUILDING
trap 'rc=$?; rm -f "$BDIR/BUILDING"; if [ $rc -ne 0 ]; then echo $rc > "$BDIR/BUILD_FAILED"; fi' EXIT
mkdir -p bin
T0=$(date +%s)
source ./env.sh
{{ echo "== host: $(hostname)  date: $(date -Is)"
   echo "== modules"; module list 2>&1 || true
   echo "== compilers"
   for c in gfortran gcc ftn cc mpif90 mpifort mpicc; do
     command -v $c >/dev/null 2>&1 && echo "$c: $(command -v $c): $($c --version 2>&1 | head -1)"
   done || true
   echo "== env"; env | grep -E '^(NETCDF|PNETCDF|HDF5|PIO|OMP|MPICH|CRAY|PE_)' | sort || true
}} > build_info.txt
{body}
{{ echo "== ldd bin/{exe}"; ldd bin/{exe} 2>&1 || true
   echo "== build seconds: $(( $(date +%s) - T0 ))"; }} >> build_info.txt
touch BUILD_OK
echo "perfsonde: {spec['name']} OK"
'''


