#!/usr/bin/env python3
"""Build every MPAS-A / WRF variant described in the site builds.yaml
(config/sites/<site>/builds.yaml).

  build_matrix.py list   [-m mpas|wrf] [--only REGEX]   show the variants
  build_matrix.py prepare ...                            copy sources, write scripts
  build_matrix.py build  ... [--mode sbatch|local] [--jobs N] [--force]
  build_matrix.py status ...                             OK / FAILED / RUNNING / ...

Each variant gets builds/<name>/ with
  env.sh      module + environment setup (also sourced by the run tests)
  build.sh    the build itself; writes BUILD_OK or BUILD_FAILED
  build.json  resolved spec (read by the ReFrame tests)
  src/        private copy of the source tree
  bin/        the executable
  *.log       configure / compile logs, build_info.txt (modules, ldd, flags)
"""

import argparse
import concurrent.futures as cf
import json
import os
import platform
import re
import shlex
import shutil
import subprocess
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__))), 'lib'))

from perfsonde import builds, site  # noqa: E402

PLATFORMS = ['serial', 'smpar', 'dmpar', 'dm+sm']


