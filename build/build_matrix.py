def select(args):
    models = [args.model] if args.model else list(builds.MODELS)
    specs = []
    for m in models:
        specs += builds.expand(m)
    if args.only:
        specs = [s for s in specs if re.search(args.only, s['name'])]
    return specs


def state(name):
    d = builds.build_dir(name)
    if builds.is_ok(name):
        return 'OK'
    if os.path.exists(os.path.join(d, 'BUILD_FAILED')):
        return 'FAILED'
    if os.path.exists(os.path.join(d, 'BUILDING')):
        return 'BUILDING'
    if os.path.exists(os.path.join(d, 'jobid')):
        return 'SUBMITTED'
    if os.path.exists(os.path.join(d, 'build.sh')):
        return 'PREPARED'
    return '-'


def cmd_list(args):
    specs = select(args)
    for s in specs:
        extra = ''
        if s['model'] == 'wrf':
            w = s.get('wrf', {})
            extra = f"parallel={w.get('parallel')} overrides={w.get('configure_overrides') or {}}"
        else:
            extra = f"target={s.get('mpas', {}).get('target')} overrides={s.get('mpas', {}).get('make_overrides') or {}}"
        print(f"{s['name']:40s} openmp={str(s['openmp']):5s} {extra}")
        if args.verbose:
            print(f"    modules: {' '.join(s.get('modules', []))}")
            for k, v in ordered_env(s.get('env') or {}):
                print(f'    env: {k}=' + ('(unset)' if v is None else str(v)))
    print(f'# {len(specs)} build variant(s)')


def prepare(spec, S, njobs):
    d = builds.build_dir(spec['name'])
    os.makedirs(d, exist_ok=True)
    print(f"[prepare] {spec['name']}: copying {spec['source']}", flush=True)
    copy_source(spec['source'], os.path.join(d, 'src'))
    if spec['model'] == 'mpas':
        m = spec.get('mpas', {})
        patch_mpas_makefile(os.path.join(d, 'src', 'Makefile'), m.get('target', 'gnu'),
                            m.get('make_overrides'))
    manifest = dict(spec)
    manifest['source_version'] = git_describe(spec['source'])
    if spec['model'] == 'wrf':
        num, desc, _ = wrf_pick_option(os.path.join(d, 'src'), spec.get('wrf', {}))
        manifest['wrf_configure_option'] = num
        manifest['wrf_configure_desc'] = desc
    write(os.path.join(d, 'build.json'), json.dumps(manifest, indent=2) + '\n')
    write(os.path.join(d, 'env.sh'), env_script(spec, S))
    write(os.path.join(d, 'build.sh'), build_script(spec, S, njobs), 0o755)
    for f in ('BUILD_OK', 'BUILD_FAILED', 'BUILDING', 'jobid'):
        if os.path.exists(os.path.join(d, f)):
            os.remove(os.path.join(d, f))
    return d


def sbatch_script(spec, S, d):
    opts = list(S['build'].get('sbatch_options', []))
    sl = S['slurm']
    if sl.get('partition') and not any(o.startswith('--partition') for o in opts):
        opts.append(f"--partition={sl['partition']}")
    if sl.get('account'):
        opts.append(f"--account={sl['account']}")
    if sl.get('qos'):
        opts.append(f"--qos={sl['qos']}")
    head = '\n'.join(f'#SBATCH {o}' for o in opts)
    return (f'#!/bin/bash\n#SBATCH --job-name=psb-{spec["name"]}\n'
            f'#SBATCH --output={d}/slurm-build-%j.out\n{head}\n'
            f'bash {shlex.quote(os.path.join(d, "build.sh"))}\n')


def run_local(spec, d):
    log = os.path.join(d, 'build_driver.log')
    with open(log, 'w') as fp:
        rc = subprocess.run(['bash', os.path.join(d, 'build.sh')], stdout=fp,
                            stderr=subprocess.STDOUT).returncode
    return spec['name'], rc


def cmd_prepare(args, submit=False):
    S = site.site()
    njobs = args.make_jobs or int(S['build'].get('make_jobs', 8))
    mode = args.mode or S['build'].get('mode', 'sbatch')
    todo = []
    for spec in select(args):
        st = state(spec['name'])
        if submit and st in ('OK', 'SUBMITTED', 'BUILDING') and not args.force:
            print(f"[skip] {spec['name']}: {st} (use --force to rebuild)")
            continue
        try:
            todo.append((spec, prepare(spec, S, njobs)))
        except Exception as exc:  # report and continue with the others
            print(f"[error] {spec['name']}: {exc}", file=sys.stderr)
    if not submit:
        print(f'# prepared {len(todo)} build(s) under {site.build_root()}')
        return
    if mode == 'sbatch':
        for spec, d in todo:
            p = os.path.join(d, 'build.sbatch')
            write(p, sbatch_script(spec, S, d), 0o755)
            res = subprocess.run(['sbatch', '--parsable', p], capture_output=True, text=True)
            if res.returncode != 0:
                print(f"[error] sbatch {spec['name']}: {res.stderr.strip()}", file=sys.stderr)
                continue
            jobid = res.stdout.strip().split(';')[0]
            write(os.path.join(d, 'jobid'), jobid + '\n')
            print(f"[submitted] {spec['name']}: job {jobid}")
    else:
        with cf.ThreadPoolExecutor(max_workers=args.jobs) as ex:
            futs = [ex.submit(run_local, spec, d) for spec, d in todo]
            for f in cf.as_completed(futs):
                name, rc = f.result()
                print(f"[{'OK' if rc == 0 else 'FAILED'}] {name}"
                      + ('' if rc == 0 else f' (see {builds.build_dir(name)}/build_driver.log)'))


def cmd_status(args):
    for spec in select(args):
        name = spec['name']
        st = state(name)
        extra = ''
        jf = os.path.join(builds.build_dir(name), 'jobid')
        if st == 'SUBMITTED' and os.path.exists(jf):
            extra = 'job ' + open(jf).read().strip()
        print(f'{name:40s} {st:10s} {extra}')


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--site', help='site profile (config/sites/<SITE>); default: auto')
    ap.add_argument('command', choices=['list', 'prepare', 'build', 'status'])
    ap.add_argument('-m', '--model', choices=builds.MODELS)
    ap.add_argument('--only', help='regex on build name')
    ap.add_argument('--mode', choices=['sbatch', 'local'], help='override site.yaml build.mode')
    ap.add_argument('--jobs', type=int, default=1, help='parallel builds in local mode')
    ap.add_argument('--make-jobs', type=int, help='make -j value')
    ap.add_argument('--force', action='store_true', help='rebuild even if OK/submitted')
    ap.add_argument('-v', '--verbose', action='store_true')
    args = ap.parse_args()
    if args.site:
        os.environ['PERFSONDE_SITE_NAME'] = args.site
    if args.command == 'list':
        cmd_list(args)
    elif args.command == 'prepare':
        cmd_prepare(args, submit=False)
    elif args.command == 'build':
        cmd_prepare(args, submit=True)
    else:
        cmd_status(args)


if __name__ == '__main__':
    main()
